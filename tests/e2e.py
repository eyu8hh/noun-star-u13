import json,sys
from playwright.sync_api import sync_playwright
R=[];errs=[]
def ok(n,c,x=''):R.append((n,bool(c)));print(('PASS ' if c else 'FAIL ')+n,x)
URL=sys.argv[1] if len(sys.argv)>1 else 'http://localhost:8765/noun-star-u13.html'
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium-1194/chrome-linux/chrome',args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':390,'height':780},has_touch=True,is_mobile=True)
    pg=ctx.new_page();pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    pg.on('dialog',lambda d:d.accept('تشكيلتي' if d.type=='prompt' else None))
    pg.goto(URL);pg.wait_for_timeout(600)
    ev=pg.evaluate
    ok('load: 150 drills',ev('S.drills.length')==150,ev('S.drills.length'))
    ok('all diagrams render',ev('S.drills.every(d=>d.dg&&dgImg(d).startsWith("data:image"))'))
    # drills CRUD + persistence
    ev('go("drills")');ev('editDrill()');pg.fill('#f1','تمرين اختبار');pg.fill('#f8','خطوة1\nخطوة2');pg.click('#modal .bt:not(.s)');pg.wait_for_timeout(300)
    pg.reload();pg.wait_for_timeout(600)
    ok('drill persists after reload',ev('S.drills.some(d=>d.name==="تمرين اختبار")') and ev('S.drills.length')==151)
    ev('go("drills")');sid=ev('S.drills.find(d=>d.src==="seed").id');n0=ev('S.drills.find(d=>d.id==="%s").name'%sid)
    ev('editDrill("%s")'%sid);pg.fill('#f1','نسخة معدلة');pg.click('#modal .bt:not(.s)');pg.wait_for_timeout(200)
    ok('edit seed keeps original',ev('S.drills.find(d=>d.id==="%s").name'%sid)==n0 and ev('S.drills.some(d=>d.name==="نسخة معدلة")'))
    ev('copyD("%s")'%sid);ev('arcD("%s")'%sid);ok('copy+archive',ev('S.drills.find(d=>d.id==="%s").status'%sid)=='مؤرشف' and ev('S.drills.length')==153);ev('arcD("%s")'%sid)
    ev('delD(S.drills.find(d=>d.name==="تمرين اختبار").id)');ok('delete w/ confirm',not ev('S.drills.some(d=>d.name==="تمرين اختبار")'))
    # board
    ev('go("board")');pg.wait_for_timeout(200)
    box=pg.locator('#cv').bounding_box()
    def pt(x,y):return (box['x']+x*box['width'],box['y']+y*box['height'])
    def tool(t):ev(f'tool="{t}";boardView()')
    tool('pa');pg.touchscreen.tap(*pt(.3,.5));pg.touchscreen.tap(*pt(.7,.5));pg.wait_for_timeout(100)
    ok('place players by tap',ev('B.frames[0].p.length')==2,ev('B.frames[0].p.length'))
    tool('move');x0=ev('B.frames[0].p[0].x')
    pg.mouse.move(*pt(.3,.5));pg.mouse.down();pg.mouse.move(*pt(.4,.6),steps=5);pg.mouse.up()
    ok('drag moves player, no stray arrow',ev('B.frames[0].a.length')==0 and abs(ev('B.frames[0].p[0].x')-x0)>.05)
    tool('pass');pg.mouse.move(*pt(.2,.7));pg.mouse.down();pg.mouse.move(*pt(.6,.7),steps=5);pg.mouse.up()
    ok('draw arrow',ev('B.frames[0].a.length')==1)
    ev('undo()');a=ev('B.frames[0].a.length');ev('doRedo()');ok('undo/redo',a==0 and ev('B.frames[0].a.length')==1)
    ev('addFrame()');ev('B.frames[1].p[0].y=.2');ev('play()');pg.wait_for_timeout(2200)
    ok('playback finishes',ev('playing')==False and ev('fi')==1)
    ev('applyForm("4-3-3")');ok('formation 4-3-3 = 11 own players',ev('B.frames[fi].p.filter(i=>i.k==="a"||i.k==="g").length')==11)
    ev('saveForm()');pg.wait_for_timeout(200);ok('custom formation saved',ev('Object.keys(S.forms).includes("تشكيلتي")'))
    ev('B.pt="half";draw()');ev('B.name="لوحة اختبار"');ev('saveB()');pg.wait_for_timeout(200)
    pg.reload();pg.wait_for_timeout(600)
    ok('board+frames persist',ev('S.boards.length')==1 and ev('S.boards[0].frames.length')==2 and ev('S.boards[0].pt')=='half' and 'تشكيلتي' in ev('Object.keys(S.forms)'))
    ev('openBoard(S.boards[0].id)');ev('exportPNG()');ok('png export',ev('document.querySelector("#modal img").src.startsWith("data:image/png")'));ev('closeM()')
    # players
    ev('editP()');pg.fill('#p1','لاعب أ');pg.fill('#p2','7');pg.click('#modal .bt:not(.s)');pg.wait_for_timeout(200)
    ev('impP()');pg.fill('#csv','الاسم,الرقم,المركز\nلاعب أ,7,ظهير\nلاعب ب,9,مهاجم\nلاعب ج,x,حارس');ev('prevP()')
    ok('csv: dup+invalid detected',ev('IMP.length')==1 and 'مكرر (يُتجاهل): 1' in ev('document.querySelector("#pv").innerText'))
    ev('doImp()');ok('csv import',ev('S.players.length')==2)
    # session
    ev('newSess()');ev('ES.name="حصة اختبار"');ev('ES.ph[0].drill=S.drills[0].id');ev('ES.att[S.players[0].id]="p"');ev('ES.eval="جيدة"');ev('saveS()')
    pg.reload();pg.wait_for_timeout(600)
    ok('session persists',ev('S.sessions.length')==1 and ev('S.sessions[0].att[S.players[0].id]')=='p' and ev('sum(S.sessions[0])')==70)
    # backup
    snap=ev('JSON.stringify(S)');ev('expB()');j=ev('$("#bk").value');ev('closeM()')
    ev('S.drills=[];S.players=[];save()');ev('impB()');pg.fill('#ib',j);ev('chkB()')
    ok('valid backup accepted',ev('!!BK'))
    ev('doB()');ok('restore: nothing lost',ev('JSON.stringify(S)')==snap or (ev('S.drills.length')==len(json.loads(snap)['drills']) and ev('S.players.length')==2))
    bad=json.loads(j);bad['data']['players'][0]['name']='مُعدّل';ev('impB()');pg.fill('#ib',json.dumps(bad));ev('chkB()')
    ok('tampered backup rejected',not ev('!!BK') and 'سلامة' in ev('document.querySelector("#ibr").innerText'))
    ev('impB()');pg.fill('#ib','{bad json');ev('chkB()');ok('corrupt json rejected',not ev('!!BK'))
    ok('no page errors',not errs,errs[:3])
    b.close()
print('%d/%d passed'%(sum(c for _,c in R),len(R)))
